#!/bin/bash
# SSH Hardening Script - Key-only Authentication
# Implements maximum security for SSH access

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

LOG_FILE="/var/log/ssh-hardening-$(date +%Y%m%d-%H%M%S).log"

echo "=== SSH Hardening Script ===" | tee -a "$LOG_FILE"
echo "Started: $(date)" | tee -a "$LOG_FILE"
echo "" | tee -a "$LOG_FILE"

# Backup function
backup_file() {
    local file=$1
    if [ -f "$file" ]; then
        cp "$file" "${file}.backup-$(date +%Y%m%d-%H%M%S)"
        echo "[+] Backed up: $file" | tee -a "$LOG_FILE"
    fi
}

# Check if running as root
if [ "$EUID" -ne 0 ]; then 
    echo -e "${RED}[!] This script must be run as root${NC}"
    exit 1
fi

# Backup SSH config
backup_file /etc/ssh/sshd_config

echo -e "${YELLOW}[*] Configuring SSH for maximum security...${NC}" | tee -a "$LOG_FILE"

# Create new hardened SSH config
cat > /etc/ssh/sshd_config << 'EOF'
# SSH Hardened Configuration
# Generated by SSH Hardening Script

# Network Settings
Port 22
AddressFamily inet
ListenAddress 0.0.0.0

# Protocol and Encryption
Protocol 2

# Host Keys - Use only strong algorithms
HostKey /etc/ssh/ssh_host_rsa_key
HostKey /etc/ssh/ssh_host_ed25519_key

# Ciphers and Algorithms - Only strong ones
Ciphers chacha20-poly1305@openssh.com,aes256-gcm@openssh.com,aes128-gcm@openssh.com,aes256-ctr,aes192-ctr,aes128-ctr
MACs hmac-sha2-512-etm@openssh.com,hmac-sha2-256-etm@openssh.com,hmac-sha2-512,hmac-sha2-256
KexAlgorithms curve25519-sha256,curve25519-sha256@libssh.org,diffie-hellman-group16-sha512,diffie-hellman-group18-sha512,diffie-hellman-group-exchange-sha256

# Authentication Settings
PermitRootLogin prohibit-password
PubkeyAuthentication yes
AuthorizedKeysFile .ssh/authorized_keys
PasswordAuthentication no
PermitEmptyPasswords no
ChallengeResponseAuthentication no
KerberosAuthentication no
GSSAPIAuthentication no
UsePAM yes

# Disable dangerous authentication methods
HostbasedAuthentication no
IgnoreRhosts yes
IgnoreUserKnownHosts yes

# Login Settings
LoginGraceTime 30
MaxAuthTries 3
MaxSessions 5
MaxStartups 10:30:60

# Disable forwarding (enable if needed)
AllowTcpForwarding no
AllowStreamLocalForwarding no
GatewayPorts no
PermitTunnel no
X11Forwarding no

# Environment
PermitUserEnvironment no
AcceptEnv LANG LC_*

# Logging
SyslogFacility AUTH
LogLevel VERBOSE

# Security Options
StrictModes yes
TCPKeepAlive yes
ClientAliveInterval 300
ClientAliveCountMax 2
Compression no
UseDNS no
PermitUserRC no

# Subsystems
Subsystem sftp /usr/lib/openssh/sftp-server -f AUTHPRIV -l INFO

# Banner
Banner /etc/ssh/banner

# Allow only specific users (uncomment and modify as needed)
# AllowUsers user1 user2
# AllowGroups sshusers

# Deny specific users
# DenyUsers baduser1 baduser2
EOF

echo -e "${GREEN}[✓] SSH configuration updated${NC}" | tee -a "$LOG_FILE"

# Create SSH banner
echo -e "${YELLOW}[*] Creating SSH banner...${NC}" | tee -a "$LOG_FILE"

cat > /etc/ssh/banner << 'EOF'
###############################################################################
#                            AUTHORIZED ACCESS ONLY                           #
###############################################################################
#                                                                             #
#  This system is for authorized use only. All activity is monitored and     #
#  logged. Unauthorized access is strictly prohibited and will be            #
#  prosecuted to the fullest extent of the law.                              #
#                                                                             #
#  By accessing this system, you consent to monitoring and recording.        #
#                                                                             #
###############################################################################
EOF

chmod 644 /etc/ssh/banner

echo -e "${GREEN}[✓] SSH banner created${NC}" | tee -a "$LOG_FILE"

# Generate strong host keys if needed
echo -e "${YELLOW}[*] Checking SSH host keys...${NC}" | tee -a "$LOG_FILE"

if [ ! -f /etc/ssh/ssh_host_ed25519_key ]; then
    echo "[+] Generating ED25519 host key..." | tee -a "$LOG_FILE"
    ssh-keygen -t ed25519 -f /etc/ssh/ssh_host_ed25519_key -N "" -q
fi

if [ ! -f /etc/ssh/ssh_host_rsa_key ]; then
    echo "[+] Generating RSA 4096 host key..." | tee -a "$LOG_FILE"
    ssh-keygen -t rsa -b 4096 -f /etc/ssh/ssh_host_rsa_key -N "" -q
fi

# Remove weak host keys
echo -e "${YELLOW}[*] Removing weak host keys...${NC}" | tee -a "$LOG_FILE"
rm -f /etc/ssh/ssh_host_dsa_key /etc/ssh/ssh_host_dsa_key.pub
rm -f /etc/ssh/ssh_host_ecdsa_key /etc/ssh/ssh_host_ecdsa_key.pub

echo -e "${GREEN}[✓] Host keys configured${NC}" | tee -a "$LOG_FILE"

# Set proper permissions
echo -e "${YELLOW}[*] Setting SSH file permissions...${NC}" | tee -a "$LOG_FILE"

chmod 600 /etc/ssh/ssh_host_*_key
chmod 644 /etc/ssh/ssh_host_*_key.pub
chmod 644 /etc/ssh/sshd_config
chmod 644 /etc/ssh/banner

echo -e "${GREEN}[✓] Permissions set${NC}" | tee -a "$LOG_FILE"

# Create SSH key setup script for users
echo -e "${YELLOW}[*] Creating SSH key setup helper script...${NC}" | tee -a "$LOG_FILE"

cat > /usr/local/bin/setup-ssh-key.sh << 'EOF'
#!/bin/bash
# SSH Key Setup Helper Script

if [ "$EUID" -ne 0 ]; then 
    echo "This script must be run as root"
    exit 1
fi

if [ -z "$1" ]; then
    echo "Usage: $0 <username>"
    echo "Example: $0 john"
    exit 1
fi

USERNAME=$1

if ! id "$USERNAME" &>/dev/null; then
    echo "Error: User $USERNAME does not exist"
    exit 1
fi

USER_HOME=$(eval echo ~$USERNAME)
SSH_DIR="$USER_HOME/.ssh"
AUTH_KEYS="$SSH_DIR/authorized_keys"

# Create .ssh directory if it doesn't exist
if [ ! -d "$SSH_DIR" ]; then
    mkdir -p "$SSH_DIR"
    echo "Created $SSH_DIR"
fi

# Set proper ownership and permissions
chown -R "$USERNAME:$USERNAME" "$SSH_DIR"
chmod 700 "$SSH_DIR"

# Create authorized_keys if it doesn't exist
if [ ! -f "$AUTH_KEYS" ]; then
    touch "$AUTH_KEYS"
    echo "Created $AUTH_KEYS"
fi

chown "$USERNAME:$USERNAME" "$AUTH_KEYS"
chmod 600 "$AUTH_KEYS"

echo ""
echo "SSH directory setup complete for user: $USERNAME"
echo "SSH directory: $SSH_DIR"
echo "Authorized keys file: $AUTH_KEYS"
echo ""
echo "To add a public key, edit: $AUTH_KEYS"
echo "Or use: echo 'ssh-rsa AAAA...' >> $AUTH_KEYS"
echo ""
echo "User can generate keys with:"
echo "  ssh-keygen -t ed25519 -C 'user@host'"
echo "  ssh-keygen -t rsa -b 4096 -C 'user@host'"
EOF

chmod +x /usr/local/bin/setup-ssh-key.sh

echo -e "${GREEN}[✓] SSH key setup script created: /usr/local/bin/setup-ssh-key.sh${NC}" | tee -a "$LOG_FILE"

# Setup SSH keys for root if not exists
echo -e "${YELLOW}[*] Checking root SSH keys...${NC}" | tee -a "$LOG_FILE"

if [ ! -d /root/.ssh ]; then
    mkdir -p /root/.ssh
    chmod 700 /root/.ssh
fi

if [ ! -f /root/.ssh/authorized_keys ]; then
    touch /root/.ssh/authorized_keys
    chmod 600 /root/.ssh/authorized_keys
    echo -e "${YELLOW}[!] IMPORTANT: Add your SSH public key to /root/.ssh/authorized_keys${NC}" | tee -a "$LOG_FILE"
    echo -e "${YELLOW}[!] Before restarting SSH, ensure you have key-based access configured!${NC}" | tee -a "$LOG_FILE"
fi

# Test SSH configuration
echo -e "${YELLOW}[*] Testing SSH configuration...${NC}" | tee -a "$LOG_FILE"

if sshd -t; then
    echo -e "${GREEN}[✓] SSH configuration is valid${NC}" | tee -a "$LOG_FILE"
else
    echo -e "${RED}[!] SSH configuration has errors!${NC}" | tee -a "$LOG_FILE"
    echo -e "${RED}[!] Restoring backup...${NC}" | tee -a "$LOG_FILE"
    cp /etc/ssh/sshd_config.backup-* /etc/ssh/sshd_config
    exit 1
fi

# Create SSH hardening check script
cat > /usr/local/bin/check-ssh-security.sh << 'EOF'
#!/bin/bash
# SSH Security Check Script

echo "=== SSH Security Status ==="
echo ""

echo "SSH Configuration:"
echo "- Root login: $(grep "^PermitRootLogin" /etc/ssh/sshd_config | awk '{print $2}')"
echo "- Password auth: $(grep "^PasswordAuthentication" /etc/ssh/sshd_config | awk '{print $2}')"
echo "- Public key auth: $(grep "^PubkeyAuthentication" /etc/ssh/sshd_config | awk '{print $2}')"
echo "- Max auth tries: $(grep "^MaxAuthTries" /etc/ssh/sshd_config | awk '{print $2}')"
echo ""

echo "Active SSH Sessions:"
who | grep pts
echo ""

echo "Recent SSH Login Attempts:"
grep "sshd" /var/log/auth.log | tail -20
echo ""

echo "SSH Service Status:"
systemctl status sshd --no-pager -l
EOF

chmod +x /usr/local/bin/check-ssh-security.sh

echo -e "${GREEN}[✓] SSH security check script created: /usr/local/bin/check-ssh-security.sh${NC}" | tee -a "$LOG_FILE"

# Warning message
echo "" | tee -a "$LOG_FILE"
echo -e "${YELLOW}╔════════════════════════════════════════════════════════════════╗${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║                    IMPORTANT WARNING                           ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}╠════════════════════════════════════════════════════════════════╣${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║ SSH has been configured for KEY-ONLY authentication            ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║                                                                ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║ Before restarting SSH, ensure you have:                        ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║ 1. Added your public key to /root/.ssh/authorized_keys        ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║ 2. Tested key-based login from another terminal               ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║                                                                ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║ To add a key: echo 'your-public-key' >> /root/.ssh/authorized_keys ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║                                                                ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║ To restart SSH: systemctl restart sshd                        ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║                                                                ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}║ If you get locked out, use Proxmox console access             ║${NC}" | tee -a "$LOG_FILE"
echo -e "${YELLOW}╚════════════════════════════════════════════════════════════════╝${NC}" | tee -a "$LOG_FILE"
echo "" | tee -a "$LOG_FILE"

echo -e "${GREEN}=== SSH Hardening Complete ===${NC}" | tee -a "$LOG_FILE"
echo "Log saved to: $LOG_FILE" | tee -a "$LOG_FILE"
echo "" | tee -a "$LOG_FILE"
echo "Helper scripts created:" | tee -a "$LOG_FILE"
echo "- /usr/local/bin/setup-ssh-key.sh <username>" | tee -a "$LOG_FILE"
echo "- /usr/local/bin/check-ssh-security.sh" | tee -a "$LOG_FILE"
